#![allow(clippy::unwrap_used)]
//! REQ: CFG-07 — `aegis hsm init|check` and `aegis index` with the tenant key in a real PKCS#11 token
//! (kryoptic, `scripts/build-kryoptic.sh`, `AEGIS_TEST_KRYOPTIC`).

use cryptoki::context::{CInitializeArgs, CInitializeFlags, Pkcs11};
use cryptoki::session::UserType;
use cryptoki::types::AuthPin;
use std::process::{Command, Output};

const PIN: &str = "pin-4be1-not-for-printing";

fn run(args: &[&str], env: &[(&str, String)]) -> (Output, String) {
    let mut c = Command::new(env!("CARGO_BIN_EXE_aegis"));
    c.args(args);
    for k in [
        "AEGIS_K_TENANT",
        "AEGIS_K_TENANT_FILE",
        "AEGIS_K_TENANT_COMMAND",
        "AEGIS_K_TENANT_PKCS11",
        "AEGIS_K_AUDIT_PKCS11",
        "AEGIS_HSM_PIN",
    ] {
        c.env_remove(k);
    }
    for (k, v) in env {
        c.env(k, v);
    }
    let o = c.output().unwrap();
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    );
    (o, text)
}

// REQ: CFG-07 — create a key inside the token, import the current one, check; the index is built with a key
// that never left the token and equals the one built with the same bytes from a file.
#[test]
fn the_cli_creates_checks_and_uses_keys_in_a_token() {
    let found = std::env::var("AEGIS_TEST_KRYOPTIC")
        .ok()
        .map(std::path::PathBuf::from)
        .filter(|p| p.exists());
    assert!(
        found.is_some() || std::env::var("AEGIS_REQUIRE_TOKEN").is_err(),
        "AEGIS_REQUIRE_TOKEN is set but kryoptic was not found (AEGIS_TEST_KRYOPTIC)"
    );
    let Some(module) = found else {
        eprintln!("SKIPPED: set AEGIS_TEST_KRYOPTIC (scripts/build-kryoptic.sh)");
        return;
    };
    let dir = std::env::temp_dir().join(format!("aegis-cli-hsm-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let conf = dir.join("token.conf");
    std::fs::write(
        &conf,
        format!(
            "[[slots]]\nslot = 1\ndbtype = \"sqlite\"\ndbargs = \"{}\"\n",
            dir.join("t.sql").display()
        ),
    )
    .unwrap();
    // an empty token with a PIN, as `softhsm2-util --init-token` would leave it
    std::env::set_var("KRYOPTIC_CONF", &conf);
    let ctx = Pkcs11::new(&module).unwrap();
    ctx.initialize(CInitializeArgs::new(CInitializeFlags::OS_LOCKING_OK))
        .unwrap();
    let slot = ctx.get_all_slots().unwrap()[0];
    let so = AuthPin::new("so-pin-0000".into());
    ctx.init_token(slot, &so, "aegis-cli").unwrap();
    let s = ctx.open_rw_session(slot).unwrap();
    s.login(UserType::So, Some(&so)).unwrap();
    s.init_pin(&AuthPin::new(PIN.into())).unwrap();
    drop(s);

    let m = module.display();
    let spec = |label: &str| format!("module={m};token=aegis-cli;label={label}");
    let env = |label: &str| -> Vec<(&str, String)> {
        vec![
            ("KRYOPTIC_CONF", conf.display().to_string()),
            ("AEGIS_K_TENANT_PKCS11", spec(label)),
            ("AEGIS_HSM_PIN", PIN.to_string()),
        ]
    };

    // nothing there yet
    let (o, text) = run(&["hsm", "check"], &env("k_t"));
    assert_eq!(o.status.code(), Some(1), "{text}");
    assert!(
        text.contains("FAIL") && text.contains("не найден"),
        "{text}"
    );

    // generated by the token
    let (o, text) = run(&["hsm", "init", "AEGIS_K_TENANT"], &env("k_t"));
    assert!(o.status.success(), "{text}");
    assert!(
        text.contains("256 бит, не извлекаемый") && text.contains("нигде больше не существует"),
        "{text}"
    );
    let (o, text) = run(&["hsm", "check"], &env("k_t"));
    assert!(o.status.success(), "{text}");
    assert!(
        text.contains("HMAC через токен") && text.contains("мкс"),
        "{text}"
    );
    // a second init does not replace the key
    let (o, text) = run(&["hsm", "init", "AEGIS_K_TENANT"], &env("k_t"));
    assert_eq!(o.status.code(), Some(1), "{text}");
    assert!(text.contains("уже есть"), "{text}");

    // a wrong PIN, and no PIN at all
    let mut bad = env("k_t");
    bad[2].1 = "wrong-pin-0e2f-not-for-printing".into();
    let (o, text) = run(&["hsm", "check"], &bad);
    assert_eq!(o.status.code(), Some(1), "{text}");
    assert!(
        !text.contains("wrong-pin-0e2f") && !text.contains(PIN),
        "{text}"
    );
    bad.pop();
    let (o, text) = run(&["hsm", "check"], &bad);
    assert_eq!(o.status.code(), Some(1), "{text}");
    assert!(text.contains("AEGIS_HSM_PIN"), "{text}");

    // import: the key bytes of today go into the token, and the index built with the token's key
    // equals the one built from the bytes
    let src = dir.join("src");
    std::fs::create_dir_all(&src).unwrap();
    std::fs::write(
        src.join("lib.rs"),
        "fn main() { let alpha = beta(gamma, delta); epsilon(alpha, zeta, eta, theta); iota(kappa, lambda, mu); nu(xi, omicron, pi, rho); }\n".repeat(8),
    )
    .unwrap();
    let old = "k-the-old-file-key-0123456789abcdef";
    let mut e = env("k_imported");
    e.push(("AEGIS_K_TENANT", old.to_string()));
    let (o, text) = run(&["hsm", "init", "AEGIS_K_TENANT", "--import"], &e);
    assert!(o.status.success(), "{text}");
    assert!(text.contains("удалите его старый источник"), "{text}");
    assert!(!text.contains(old), "the key is printed: {text}");
    let repo = format!("r={}", src.display());
    let (o, text) = run(
        &[
            "index",
            "build",
            "--repo",
            &repo,
            "-o",
            dir.join("hsm.idx").to_str().unwrap(),
        ],
        &env("k_imported"),
    );
    assert!(o.status.success(), "{text}");
    let (o, text) = run(
        &[
            "index",
            "build",
            "--repo",
            &repo,
            "-o",
            dir.join("file.idx").to_str().unwrap(),
        ],
        &[("AEGIS_K_TENANT", old.to_string())],
    );
    assert!(o.status.success(), "{text}");
    assert_eq!(
        std::fs::read(dir.join("hsm.idx")).unwrap(),
        std::fs::read(dir.join("file.idx")).unwrap(),
        "the index built with the key in the token differs from the one built with its bytes"
    );
    // an index built with the other (generated) key does not open with this one
    let (o, _) = run(
        &[
            "index",
            "build",
            "--repo",
            &repo,
            "-o",
            dir.join("other.idx").to_str().unwrap(),
        ],
        &env("k_t"),
    );
    assert!(o.status.success());
    let (o, text) = run(
        &["index", "info", dir.join("other.idx").to_str().unwrap()],
        &env("k_imported"),
    );
    assert!(!o.status.success(), "{text}");
    let _ = std::fs::remove_dir_all(dir);
}
